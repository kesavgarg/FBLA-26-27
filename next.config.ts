import type { NextConfig } from "next";

/**
 * Next.js configuration for the Goodson Drug Co. ordering platform.
 *
 * We use the classic dynamic rendering model (no `cacheComponents`): any page
 * that reads the signed-in user's cookies renders fresh on every request.
 * That keeps one customer's data from ever being cached for another.
 */
const nextConfig: NextConfig = {
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  images: {
    // Product photographs are stored locally in /public/products.
    formats: ["image/avif", "image/webp"],
  },
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: [
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
        ],
      },
    ];
  },
};

export default nextConfig;
